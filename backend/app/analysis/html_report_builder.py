"""Minimal HTML report for a completed analysis (analysis.md §7.3 MVP)."""

from __future__ import annotations

import html
from typing import Any, Dict, List


class AnalysisHtmlReportBuilder:
    """Builds a self-contained HTML document (no external assets)."""

    @staticmethod
    def build(doc: Dict[str, Any]) -> str:
        meta = doc.get("metadata") or {}
        summary = doc.get("summary") or {}
        moves: List[Dict[str, Any]] = doc.get("moves") or []
        w = html.escape(str(meta.get("white", "White")))
        b = html.escape(str(meta.get("black", "Black")))
        res = html.escape(str(meta.get("result", "*")))
        eco = html.escape(str(meta.get("eco", "")))
        opn = html.escape(str(meta.get("opening", "")))
        wa = summary.get("white_accuracy")
        ba = summary.get("black_accuracy")
        crit: List[str] = []
        for i, m in enumerate(moves):
            cl = m.get("classification")
            if cl in ("blunder", "miss", "mistake"):
                crit.append(
                    f"<li>Ply {i + 1}: {html.escape(str(m.get('move', '')))} — "
                    f"<strong>{html.escape(str(cl))}</strong></li>"
                )
        crit_html = "\n".join(crit[:24]) or "<li>None flagged in this pass.</li>"
        head = f"{w} vs {b} ({res})"
        return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/><title>{head}</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:720px;margin:2rem auto;padding:0 1rem;line-height:1.45}}
h1{{font-size:1.25rem}}
.meta{{color:#555;font-size:0.9rem}}
ul{{padding-left:1.2rem}}
</style></head><body>
<h1>{head}</h1>
<p class="meta">{eco} {opn}</p>
<p><strong>Accuracy</strong>: White {wa} · Black {ba}</p>
<h2>Critical moments</h2>
<ul>
{crit_html}
</ul>
<p class="meta">Generated by ChessEval · FENs available via API export.</p>
</body></html>"""
